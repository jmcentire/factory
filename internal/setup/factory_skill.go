// coderSwap keeps the Coder off the Validator's model family: the Validator is
// whichever agent runs /factory, so when that is the Coder seat's own family the
// Coder moves to the other of Claude and Codex.
type coderSwap struct {
	Host string // the Coder seat's family, as a /factory loader names its agent
	Seat Seat   // the Coder to use instead
}

// modelFamily names the hosted model family a seat agent runs, as a /factory
// loader names its agent; "" for a local (Ollama) model or one this does not track.
func modelFamily(agent string) string {
	switch agent {
	case "codex", "codex-interactive":
		return "codex"
	case "claude", "agy", "prime-agent":
		return agent
	}
	return ""
}

// seatFamily is a seat's model family: its model's when one is named (agy can run
// a Claude model), else its agent's.
func seatFamily(s Seat) string {
	switch {
	case strings.HasPrefix(s.Model, "claude-"):
		return "claude"
	case strings.HasPrefix(s.Model, "gpt-"):
		return "codex"
	case strings.HasPrefix(s.Model, "gemini-"):
		return "agy"
	}
	return modelFamily(s.Agent)
}

// coderSwapFor moves the Coder to the configured Validator seat's agent, which
// setup installs, preflights and checks sign-in for, when /factory runs in the
// Coder's own family. A Coder the human named at setup is never swapped, and the
// swap never lands on the Tester's family: the Factory requires Coder and Tester to
// run different model families.
func coderSwapFor(s Seats, chosen bool) *coderSwap {
	host := modelFamily(s.Coder.Agent)
	target := modelFamily(s.Validator.Agent)
	if chosen || host == "" || target == "" || target == host || target == seatFamily(s.Tester) ||
		!slices.Contains(laneAgents, s.Validator.Agent) {
		return nil
	}
	return &coderSwap{Host: host, Seat: s.Validator}
}

