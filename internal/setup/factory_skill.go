// skillFuncs render a seat in the skill's table and on a lane's launch line.
var skillFuncs = template.FuncMap{
	"seat": func(s Seat) string {
		if s.Model == "" {
			return "`" + s.Agent + "` (its own default model)"
		}
		return "`" + s.Agent + "` on `" + s.Model + "`"
	},
	"laneFlags": func(s Seat) string {
		if s.Model == "" {
			return "--agent " + s.Agent
		}
		return "--agent " + s.Agent + " --model " + s.Model
	},
}

// seatPreflight lists one check per executable the seats run, in seat order.
func seatPreflight(env *Env, s Seats) []string {
	var bins []string
	for _, seat := range []Seat{s.Validator, s.Orchestrator, s.Coder, s.Tester} {
		need := []string{seatBinary(seat.Agent)}
		if strings.Contains(seat.Agent, "ollama") {
			need = append(need, "ollama")
		}
		for _, b := range need {
			if !slices.Contains(bins, b) {
				bins = append(bins, b)
			}
		}
	}
	var out []string
	for _, b := range bins {
		state := "present"
		if _, ok := env.Have(b); !ok {
			state = "MISSING: " + seatInstall(b)
		}
		out = append(out, fmt.Sprintf("%-48s# %s", "command -v "+b+" && "+b+" --version", state))
	}
	// This session's PATH is the run's: hold each seat agent to the pinned Factory's
	// contract, updating one that falls short.
	var checked []string
	for _, seat := range []Seat{s.Validator, s.Orchestrator, s.Coder, s.Tester} {
		if contractAgents[seat.Agent] && !slices.Contains(checked, seat.Agent) {
			checked = append(checked, seat.Agent)
			out = append(out, contractPreflight(seat.Agent)+"  # runs "+seat.Agent+"'s own update, brew or npm if it falls short of this Factory; report it if still short")
		}
	}
	for _, model := range agyModelsRun(s) {
		check := `"$(command -v timeout || command -v gtimeout)" 60 agy models </dev/null | cut -f1 | grep -Fx ` + model
		out = append(out, fmt.Sprintf("%-48s# if absent: sign out of agy, %s", check+" ", agySignIn(model)))
	}
	return out
}

func renderFactorySkill(env *Env) ([]byte, error) {
	o := env.Opts
	// The agent list reflects the machine, not this run's selection, so a
	// later `--components factory` re-run is a no-op.
	wired := agentsWithFactoryLoader(o)
	var agentNames []string
	for _, id := range wired {
		if a, ok := agentByID(id); ok {
			agentNames = append(agentNames, a.Name+" (/factory)")
		}
	}
	if len(agentNames) == 0 {
		agentNames = []string{"none yet; loaders are written when agents are configured"}
	}
	_, haveTmux := env.Have("tmux")
	d := skillData{
		Publishing:    docs.FactoryPublishing,
		Generated:     skillMarker + "\n<!-- generated " + nowUTC() + "; do not edit, re-run factory-setup -->",
		FactoryHome:   o.FactoryDir(),
		RunCheckout:   o.RunCheckoutPath(),
		Seats:         o.Seats,
		Preflight:     seatPreflight(env, o.Seats),
		HaveTmux:      haveTmux,
		Agents:        agentNames,
		PromptsReadme: filepath.Join(o.FactoryDir(), "prompts", "README.md"),
		CoderSwap:     coderSwapFor(o.Seats, o.CoderChosen),
	}
	var b strings.Builder
	if err := skillTemplate.Execute(&b, d); err != nil {
		return nil, err
	}
	return []byte(b.String()), nil
}

func (factorySkillStep) Check(_ context.Context, env *Env) (Status, string, error) {
	if err := env.Opts.Seats.Validate(); err != nil {
		return StatusBlocked, err.Error(), nil
	}
	want, err := renderFactorySkill(env)
	if err != nil {
		return StatusBlocked, err.Error(), nil
	}
	have, err := os.ReadFile(env.Opts.SkillPath())
	if err != nil || stripGenerated(string(have)) != stripGenerated(string(want)) {
		return StatusMissing, "", nil
	}
	script, err := os.ReadFile(env.Opts.RunCheckoutPath())
	if st, serr := os.Stat(env.Opts.RunCheckoutPath()); err != nil || serr != nil ||
		string(script) != string(runCheckoutScript) || st.Mode().Perm()&0o100 == 0 {
		return StatusMissing, "", nil
	}
	return StatusDone, env.Opts.SkillPath(), nil
}

func (factorySkillStep) Apply(_ context.Context, env *Env) error {
	b, err := renderFactorySkill(env)
	if err != nil {
		return err
	}
	if err := env.WriteFile(env.Opts.RunCheckoutPath(), runCheckoutScript, 0o755); err != nil {
		return err
	}
	return env.WriteFile(env.Opts.SkillPath(), b, 0o644)
}

// stripGenerated removes the timestamp comment so an unchanged skill is a
// no-op on re-run.
func stripGenerated(s string) string {
	lines := strings.SplitN(s, "\n", 3)
	if len(lines) == 3 && strings.HasPrefix(lines[1], "<!-- generated ") {
		return lines[0] + "\n" + lines[2]
	}
	return s
}
