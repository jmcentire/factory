// agentsWithFactoryLoader lists agents selected in this run or already
// carrying a /factory loader on disk, in menu order.
func agentsWithFactoryLoader(o Options) []AgentID {
	var out []AgentID
	for _, a := range agents {
		if o.HasAgent(a.ID) || Exists(factoryLoaderPath(o, a.ID)) {
			out = append(out, a.ID)
		}
	}
	return out
}

// factoryLoaderPath is where each agent's /factory loader lives.
func factoryLoaderPath(o Options, id AgentID) string {
	switch id {
	case AgentClaude:
		c, _, _ := claudePaths(o)
		return filepath.Join(c, "factory.md")
	case AgentCodex:
		s, _, _ := codexPaths(o)
		return filepath.Join(s, "factory", "SKILL.md")
	case AgentOpenCode:
		c, _, _ := opencodePaths(o)
		return filepath.Join(c, "factory.md")
	case AgentPrime:
		p, _, _ := piLayout(primeRoot(o), primeMCPFile)
		return filepath.Join(p, "factory.md")
	case AgentPi:
		p, _, _ := piLayout(piRoot(o), piMCPFile)
		return filepath.Join(p, "factory.md")
	case AgentAntigravity:
		s, _, _ := antigravityPaths(o)
		return filepath.Join(s, "factory", "SKILL.md")
	}
	return ""
}

